"""PostgreSQL տվյալների բազա (psycopg 3, connection pool).
Կապը՝ DATABASE_URL փոփոխականով (լռելյայն՝ docker-compose-ի տեղական բազան)։
Հրամաններ՝
  python db.py reset                      # ջնջել աղյուսակները և նորից լցնել նմուշային տվյալներով
  python db.py set-price ԳԱՐԱԺ ԾԱՌԱՅՈՒԹՅՈՒՆ ԳԻՆ   # օր.՝ python db.py set-price 3 2 13000
  python db.py show                       # ցույց տալ գները
  python db.py import-sqlite ՖԱՅԼ         # հին SQLite բազայի տվյալները տեղափոխել դատարկ Postgres-ի մեջ
"""
import os
import sys

import psycopg
from psycopg.rows import dict_row
from psycopg.types.datetime import TimestamptzLoader
from psycopg_pool import ConnectionPool

from data import GARAGES, SERVICES

DEFAULT_URL = "postgresql://autoservice:autoservice@127.0.0.1:5433/autoservice"
DATABASE_URL = os.getenv("DATABASE_URL", DEFAULT_URL)

# Ժամանակները պահվում են timestamptz-ով (վայրկյանի ճշտությամբ), բայց կոդին և API-ին տրվում են
# նախկին ձևով՝ "YYYY-MM-DD HH:MM:SS" UTC տող։ Սեսիայի ժամային գոտին UTC է (տե՛ս _POOL_KWARGS)։
class UtcTextLoader(TimestamptzLoader):
    def load(self, data) -> str:  # type: ignore[override]
        return bytes(data).decode()[:19]


_POOL_KWARGS = {"row_factory": dict_row, "options": "-c timezone=UTC"}

REQUESTS_DDL = """
CREATE TABLE IF NOT EXISTS requests (           -- վարորդների հայտերը
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMPTZ(0) NOT NULL DEFAULT now(),
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    garage_id INTEGER REFERENCES garages(id) ON DELETE SET NULL,
    service_id INTEGER REFERENCES services(id) ON DELETE SET NULL,
    message TEXT NOT NULL DEFAULT '',
    -- փուլեր՝ new նոր, called զանգահարվել է, no_answer չպատասխանեց, booked ժամ պայմանավորվեց,
    -- visited այցելեց, declined հրաժարվեց
    status TEXT NOT NULL DEFAULT 'new'
        CHECK (status IN ('new','called','no_answer','booked','visited','declined')),
    decline_reason TEXT
        CHECK (decline_reason IS NULL OR decline_reason IN ('price','far','other_garage','no_time','changed_mind','other')),
    status_changed_at TIMESTAMPTZ(0),
    first_response_at TIMESTAMPTZ(0),            -- առաջին անգամ «նոր»-ից դուրս գալու պահը
    review_token TEXT                            -- վարորդի գաղտնի հղում՝ գնահատելու համար (գարաժը չի տեսնում)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_requests_review_token ON requests(review_token) WHERE review_token IS NOT NULL;
"""

REVIEWS_DDL = """
CREATE TABLE IF NOT EXISTS reviews (             -- վարորդի հաստատումը և գնահատականը (մեկ հայտ = մեկ կարծիք)
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    request_id INTEGER NOT NULL UNIQUE REFERENCES requests(id) ON DELETE CASCADE,
    garage_id INTEGER NOT NULL REFERENCES garages(id) ON DELETE CASCADE,
    service_id INTEGER REFERENCES services(id) ON DELETE SET NULL,
    phone_key TEXT NOT NULL,                     -- հեռախոսի վերջին 8 թվանշանը՝ կրկնակի կարծիքներից պաշտպանվելու համար
    went INTEGER NOT NULL CHECK (went IN (0, 1)),
    rating INTEGER CHECK (rating BETWEEN 1 AND 5),
    comment TEXT NOT NULL DEFAULT '',
    reason TEXT CHECK (reason IS NULL OR reason IN ('price','far','other_garage','no_time','changed_mind','other')),
    display_name TEXT NOT NULL DEFAULT '',
    hidden INTEGER NOT NULL DEFAULT 0,
    hidden_reason TEXT,
    created_at TIMESTAMPTZ(0) NOT NULL DEFAULT now(),
    CHECK ((went = 1 AND rating IS NOT NULL) OR (went = 0 AND rating IS NULL))
);
CREATE INDEX IF NOT EXISTS ix_reviews_garage ON reviews(garage_id);
"""

SCHEMA = """
CREATE TABLE IF NOT EXISTS services (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    keywords TEXT NOT NULL DEFAULT '',         -- ստորակետով բաժանված
    sample_question TEXT NOT NULL DEFAULT ''   -- օրինակ հարց chat-ի «հաճախ հարցվող» chip-ի համար
);
CREATE TABLE IF NOT EXISTS garages (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    address TEXT NOT NULL,
    phone TEXT NOT NULL,
    login TEXT,                                 -- գարաժի սեփականատիրոջ մուտքանունը (փոքրատառ)
    password_hash TEXT,
    telegram_chat_id BIGINT,
    lat DOUBLE PRECISION,                       -- հաստատված կետ քարտեզի վրա
    lng DOUBLE PRECISION
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_garages_login ON garages(login) WHERE login IS NOT NULL;
CREATE TABLE IF NOT EXISTS link_codes (          -- Telegram կապի մեկանգամյա կոդեր (վավեր 1 ժամ)
    code TEXT PRIMARY KEY,
    kind TEXT NOT NULL CHECK (kind IN ('garage','admin')),
    garage_id INTEGER REFERENCES garages(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ(0) NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS garage_services (
    garage_id INTEGER NOT NULL REFERENCES garages(id) ON DELETE CASCADE,
    service_id INTEGER NOT NULL REFERENCES services(id) ON DELETE CASCADE,
    price INTEGER NOT NULL CHECK (price >= 0),  -- դրամ
    duration_min INTEGER NOT NULL CHECK (duration_min > 0),
    PRIMARY KEY (garage_id, service_id)
);
CREATE TABLE IF NOT EXISTS working_hours (      -- միայն բաց օրերը
    garage_id INTEGER NOT NULL REFERENCES garages(id) ON DELETE CASCADE,
    weekday INTEGER NOT NULL CHECK (weekday BETWEEN 0 AND 6),  -- 0 = Երկուշաբթի
    open_time TEXT NOT NULL,                     -- "HH:MM"
    close_time TEXT NOT NULL,
    PRIMARY KEY (garage_id, weekday)
);
CREATE TABLE IF NOT EXISTS chat_queries (       -- վարորդների առաջին հարցերը. «հաճախ հարցվող» chip-երի համար
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMPTZ(0) NOT NULL DEFAULT now(),
    text TEXT NOT NULL,                          -- առավելագույնը 200 նիշ, առանց անձնական տվյալների
    service_id INTEGER REFERENCES services(id) ON DELETE SET NULL,  -- որ ծառայությանը հասցրեց chat-ը (NULL՝ չգտնվեց)
    mode TEXT NOT NULL DEFAULT 'simple'
);
CREATE INDEX IF NOT EXISTS ix_chat_queries_created ON chat_queries(created_at);
""" + REQUESTS_DDL + REVIEWS_DDL

TABLES = ("services", "garages", "garage_services", "working_hours", "requests", "reviews", "link_codes", "settings",
          "chat_queries")
SERIAL_TABLES = ("services", "garages", "requests", "reviews", "chat_queries")

_pool: ConnectionPool | None = None
_ready: set[str] = set()


def _configure(conn: psycopg.Connection) -> None:
    conn.adapters.register_loader("timestamptz", UtcTextLoader)


def _get_pool() -> ConnectionPool:
    global _pool
    if _pool is None:
        _pool = ConnectionPool(DATABASE_URL, min_size=1, max_size=10, kwargs=_POOL_KWARGS,
                               configure=_configure, open=True)
    return _pool


def _migrate(conn: psycopg.Connection) -> None:
    """Արդեն գոյություն ունեցող բազաներին ավելացնում է նոր սյուները (տվյալները չեն կորչում)։"""
    for name, decl in (("login", "TEXT"), ("password_hash", "TEXT"), ("telegram_chat_id", "BIGINT"),
                       ("lat", "DOUBLE PRECISION"), ("lng", "DOUBLE PRECISION")):
        conn.execute(f"ALTER TABLE garages ADD COLUMN IF NOT EXISTS {name} {decl}")
    conn.execute("ALTER TABLE requests ADD COLUMN IF NOT EXISTS review_token TEXT")
    conn.execute("ALTER TABLE services ADD COLUMN IF NOT EXISTS sample_question TEXT NOT NULL DEFAULT ''")


def _fix_sequences(conn: psycopg.Connection) -> None:
    """Բացահայտ id-ներով տող ավելացնելուց հետո հաջորդականությունները տանում ենք առավելագույնին։"""
    for t in SERIAL_TABLES:
        conn.execute(f"SELECT setval(pg_get_serial_sequence('{t}','id'), COALESCE((SELECT MAX(id) FROM {t}), 0) + 1, false)")


def _ensure_schema() -> None:
    if DATABASE_URL in _ready:
        return
    with _get_pool().connection() as conn:
        conn.execute(SCHEMA)
        _migrate(conn)
        if (os.getenv("SEED_SAMPLE", "1") == "1"
                and conn.execute("SELECT COUNT(*) AS n FROM services").fetchone()["n"] == 0):
            seed(conn)
    _ready.add(DATABASE_URL)


def connect():
    """Կապ pool-ից, `with connect() as c:` ձևով. ելքին commit է անում (սխալի դեպքում՝ rollback)։
    Առաջին անգամ ստեղծում է աղյուսակները և լցնում նմուշային տվյալները։"""
    _ensure_schema()
    return _get_pool().connection()


def seed(conn: psycopg.Connection) -> None:
    for s in SERVICES:
        conn.execute("INSERT INTO services(id,name,category,keywords,sample_question) VALUES (%s,%s,%s,%s,%s)",
                     (s.id, s.name, s.category, ",".join(s.keywords), s.sample_question))
    for g in GARAGES:
        conn.execute("INSERT INTO garages(id,name,address,phone) VALUES (%s,%s,%s,%s)", (g.id, g.name, g.address, g.phone))
        for day, (o, c) in g.hours.items():
            conn.execute("INSERT INTO working_hours VALUES (%s,%s,%s,%s)",
                         (g.id, day, f"{o:%H:%M}", f"{c:%H:%M}"))
        for gs in g.services.values():
            conn.execute("INSERT INTO garage_services VALUES (%s,%s,%s,%s)",
                         (g.id, gs.service_id, gs.price, gs.duration_min))
    _fix_sequences(conn)


def reset() -> None:
    """Ջնջում է բոլոր աղյուսակները և նորից ստեղծում (SEED_SAMPLE=1-ի դեպքում՝ նմուշային տվյալներով)։"""
    with _get_pool().connection() as conn:
        conn.execute("DROP TABLE IF EXISTS " + ", ".join(TABLES) + " CASCADE")
    _ready.discard(DATABASE_URL)
    _ensure_schema()


def close() -> None:
    """Փակում է pool-ը (թեստերի վերջում, ժամանակավոր բազան ջնջելուց առաջ)։"""
    global _pool
    if _pool is not None:
        _pool.close()
        _pool = None
    _ready.discard(DATABASE_URL)


def import_sqlite(path: str) -> dict[str, int]:
    """Հին SQLite բազայի բոլոր տողերը տեղափոխում է Postgres։ Միայն դատարկ Postgres-ի մեջ,
    որպեսզի id-ները չբախվեն։ Հին «done» փուլը դառնում է «called»։ Վերադարձնում է աղյուսակ -> տողերի քանակ։"""
    import sqlite3
    src = sqlite3.connect(path)
    src.row_factory = sqlite3.Row
    old_tables = {r[0] for r in src.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    os.environ["SEED_SAMPLE"] = "0"           # ներմուծվող բազան չպետք է նախապես լցվի նմուշով
    _ensure_schema()
    counts: dict[str, int] = {}
    with _get_pool().connection() as conn:
        if conn.execute("SELECT COUNT(*) AS n FROM services").fetchone()["n"]:
            raise SystemExit("Postgres բազան դատարկ չէ. ներմուծումը հնարավոր է միայն դատարկ բազայի մեջ (python db.py reset)")
        pg_cols = {t: [r["column_name"] for r in conn.execute(
            "SELECT column_name FROM information_schema.columns WHERE table_name=%s ORDER BY ordinal_position", (t,))]
            for t in TABLES}
        for t in TABLES:                       # FK-ների կարգով
            if t not in old_tables:
                continue
            rows = src.execute(f"SELECT * FROM {t}").fetchall()
            cols = [c for c in rows[0].keys() if c in pg_cols[t]] if rows else []
            for r in rows:
                vals = [r[c] for c in cols]
                if t == "requests" and "status" in cols:
                    i = cols.index("status")
                    vals[i] = "called" if vals[i] == "done" else vals[i]
                conn.execute(f"INSERT INTO {t} ({', '.join(cols)}) VALUES ({', '.join(['%s'] * len(cols))})", vals)
            counts[t] = len(rows)
        _fix_sequences(conn)
    src.close()
    return counts


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "reset":
        reset()
        print("Բազան վերականգնված է՝", DATABASE_URL.rsplit("@", 1)[-1])
    elif cmd == "set-price" and len(sys.argv) == 5:
        from queries import set_price
        ok = set_price(int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4]))
        print("Գինը թարմացվեց ✓" if ok else "Այդպիսի գարաժ/ծառայություն չկա")
    elif cmd == "show":
        with connect() as c:
            for r in c.execute("""SELECT g.id gid, g.name g, s.id sid, s.name s, gs.price
                                  FROM garage_services gs JOIN garages g ON g.id = gs.garage_id
                                  JOIN services s ON s.id = gs.service_id ORDER BY g.id, s.id"""):
                print(f"[{r['gid']}] {r['g']:16} [{r['sid']}] {r['s']:42} {r['price']:>7,} ֏")
    elif cmd == "import-sqlite" and len(sys.argv) == 3:
        for t, n in import_sqlite(sys.argv[2]).items():
            print(f"{t:16} {n:>5} տող")
        print("Ներմուծումը ավարտված է ✓")
    else:
        print(__doc__)
